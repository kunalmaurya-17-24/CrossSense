"""Tiny deterministic georeferenced fixtures; never a substitute for satellite evidence."""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import rasterio
from rasterio.transform import from_origin

from crosssense.data.pairing import _get

logger = logging.getLogger(__name__)


def create_synthetic_fixture(output_dir: str | Path, data_config: Any, seed: int = 42) -> Path:
    """Create 36 paired patches across nine separated mock regions as GeoTIFF scenes.

    Shared random spatial patterns create artificial correspondence; neither
    values nor labels support claims about real Sentinel imagery performance.
    """
    output_dir = Path(output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    size = int(_get(data_config, "patch_size", 32))
    res = float(_get(data_config, "resolution_m", 10))
    crs = str(_get(data_config, "target_crs", "EPSG:32643"))
    scene_size = size * 2
    spacing = max(float(_get(data_config, "block_size_m", 10000)) * 3,
                  float(_get(data_config, "split_buffer_m", 500)) * 4 + scene_size * res * 2)
    records = []
    for region in range(9):
        latent = np.zeros((scene_size, scene_size), dtype=np.float32)
        y_grid, x_grid = np.mgrid[:size, :size].astype(np.float32) / size
        for row in range(2):
            for col in range(2):
                angle = rng.uniform(0, 2 * np.pi)
                freq = rng.uniform(1, 4)
                base = rng.uniform(.2, .7)
                texture = base + .12 * np.sin(2 * np.pi * freq * (x_grid * np.cos(angle) + y_grid * np.sin(angle)))
                texture += .06 * np.cos(2 * np.pi * rng.uniform(1, 5) * y_grid)
                texture += rng.normal(0, .01, (size, size))
                latent[row * size:(row + 1) * size, col * size:(col + 1) * size] = np.clip(texture, .02, .98)
        sar_normalized = np.stack([latent, .15 + .7 * latent])
        sar = sar_normalized * 35 - 30
        optical = np.stack([np.clip(latent * (0.8 + channel * .025) + .015 * channel, 0, 1)
                            for channel in range(13)]) * 10000
        transform = from_origin(450000 + region * spacing, 1450000, res, res)
        files = {"sar": output_dir / f"synthetic_region{region}_sar.tif",
                 "optical": output_dir / f"synthetic_region{region}_optical.tif",
                 "cloud": output_dir / f"synthetic_region{region}_cloud.tif"}
        for sensor, array in [("sar", sar), ("optical", optical),
                              ("cloud", np.zeros((1, scene_size, scene_size), dtype=np.float32))]:
            with rasterio.open(files[sensor], "w", driver="GTiff", width=scene_size, height=scene_size,
                               count=array.shape[0], dtype="float32", crs=crs, transform=transform,
                               nodata=-9999, compress="deflate") as dst:
                dst.write(array.astype(np.float32))
                dst.update_tags(source="SYNTHETIC_FIXTURE", seed=seed, region=region)
        for sensor in ["sar", "optical"]:
            names = ["VV", "VH"] if sensor == "sar" else ["B1", "B2", "B3", "B4", "B5", "B6", "B7", "B8", "B8A", "B9", "B10", "B11", "B12"]
            records.append({"scene_id": f"synthetic-region{region}-{sensor}", "sensor": sensor,
                            "path": files[sensor].name, "timestamp": f"2024-01-{10 if sensor == 'sar' else 12:02d}T00:00:00Z",
                            "source": "synthetic", "band_names": json.dumps(names),
                            "cloud_mask_path": files["cloud"].name if sensor == "optical" else "",
                            "land_cover": ["synthetic_urban", "synthetic_rural", "synthetic_water"][region % 3],
                            "sar_units": "db", "reflectance_scale": 10000, "reflectance_offset": 0,
                            "license": "synthetic fixture generated by CrossSense", "attribution": "CrossSense synthetic test data"})
    manifest = output_dir / "scenes.csv"
    pd.DataFrame(records).to_csv(manifest, index=False)
    logger.warning("Created SYNTHETIC fixture: %s scenes=%d seed=%d; no satellite data used", manifest, len(records), seed)
    return manifest
